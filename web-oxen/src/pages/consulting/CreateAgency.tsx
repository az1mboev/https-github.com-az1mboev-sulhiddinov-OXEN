import { useRef, useState } from "react";
import { motion, AnimatePresence } from "framer-motion";
import { useNavigate } from "react-router-dom";
import {
  Building2, Upload, Loader2, ArrowLeft, Check, Sparkles,
  Phone, Mail, MessageCircle, Send, Instagram, Calendar,
  MapPin, FileText, X, Image as ImageIcon,
} from "lucide-react";

import { useAuth } from "@/contexts/AuthContext";
import { useConsulting } from "@/contexts/ConsultingContext";
import { useSEO } from "@/hooks/use-seo";
import { toast } from "@/hooks/use-toast";
import { createNewAgency, uploadConsultingAsset } from "@/lib/consulting";
import { COUNTRIES } from "@/data/countries";
import { cn } from "@/lib/utils";

const springIn = {
  type: "spring" as const,
  stiffness: 260,
  damping: 26,
};

interface FormData {
  name: string;
  country: string;
  city: string;
  logoUrl: string | null;
  contactPhone: string;
  contactEmail: string;
  whatsapp: string;
  telegram: string;
  instagram: string;
  description: string;
  foundedYear: string;
  address: string;
  agencyPhotos: string[];
  licenseNumber: string;
  licenseIssuingOrg: string;
}

interface FormErrors {
  name?: string;
  logoUrl?: string;
  country?: string;
}

const initialForm: FormData = {
  name: "",
  country: "",
  city: "",
  logoUrl: null,
  contactPhone: "",
  contactEmail: "",
  whatsapp: "",
  telegram: "",
  instagram: "",
  description: "",
  foundedYear: "",
  address: "",
  agencyPhotos: [],
  licenseNumber: "",
  licenseIssuingOrg: "",
};

/**
 * CreateAgency — form to create a new travel agency workspace.
 *
 * Required fields: Agency Name, Logo, Country.
 * Optional fields: City, Phone, WhatsApp, Telegram, Instagram, Email,
 *   Description, Founded Year, Address, Agency Photos, License info.
 *
 * On submit:
 * - Creates consulting_companies row (agency_code auto-generated by DB trigger)
 * - Creates consulting_members row with role=owner (upsert for retry safety)
 * - Sets this agency as active
 * - Redirects to dashboard
 */
export default function CreateAgency() {
  const navigate = useNavigate();
  const { user } = useAuth();
  const { switchAgency, refresh } = useConsulting();
  const fileRef = useRef<HTMLInputElement>(null);
  const photoRef = useRef<HTMLInputElement>(null);

  const [form, setForm] = useState<FormData>(initialForm);
  const [errors, setErrors] = useState<FormErrors>({});
  const [uploadingLogo, setUploadingLogo] = useState(false);
  const [uploadingPhotos, setUploadingPhotos] = useState(false);
  const [creating, setCreating] = useState(false);

  useSEO({
    title: "Create Agency | OXEN CRM",
    description: "Create a new travel agency workspace.",
  });

  const set = <K extends keyof FormData>(key: K, value: FormData[K]) => {
    setForm((prev) => ({ ...prev, [key]: value }));
    if (key === "name" && errors.name) setErrors({});
    if (key === "logoUrl" && errors.logoUrl) setErrors({});
    if (key === "country" && errors.country) setErrors({});
  };

  const validate = (): boolean => {
    const errs: FormErrors = {};
    if (!form.name.trim()) {
      errs.name = "Agency name is required.";
    } else if (form.name.trim().length < 2) {
      errs.name = "Name must be at least 2 characters.";
    }
    if (!form.logoUrl) {
      errs.logoUrl = "Agency logo is required.";
    }
    if (!form.country) {
      errs.country = "Country is required.";
    }
    setErrors(errs);
    return Object.keys(errs).length === 0;
  };

  const handleLogoUpload = async (file: File) => {
    if (!user) return;
    if (file.size > 2 * 1024 * 1024) {
      toast({ title: "Image too large", description: "Max 2 MB.", variant: "destructive" });
      return;
    }
    // Preview locally first
    const reader = new FileReader();
    reader.onload = () => set("logoUrl", reader.result as string);
    reader.readAsDataURL(file);

    // Upload to storage
    setUploadingLogo(true);
    try {
      const url = await uploadConsultingAsset(file, `logos/${user.id}/logo-${Date.now()}`);
      if (url) {
        set("logoUrl", url);
        toast({ title: "Logo uploaded" });
      }
    } catch {
      // Keep the data URL preview — will upload again after company is created
    } finally {
      setUploadingLogo(false);
    }
  };

  const handlePhotoUpload = async (files: FileList) => {
    if (!user) return;
    const newPhotos: string[] = [];
    setUploadingPhotos(true);
    try {
      for (const file of Array.from(files)) {
        if (file.size > 3 * 1024 * 1024) {
          toast({ title: "Image too large", description: `${file.name} exceeds 3 MB.`, variant: "destructive" });
          continue;
        }
        const url = await uploadConsultingAsset(file, `agency-photos/${user.id}/photo-${Date.now()}-${file.name}`);
        if (url) newPhotos.push(url);
      }
      if (newPhotos.length > 0) {
        set("agencyPhotos", [...form.agencyPhotos, ...newPhotos]);
        toast({ title: `${newPhotos.length} photo(s) uploaded` });
      }
    } catch {
      toast({ title: "Photo upload failed", variant: "destructive" });
    } finally {
      setUploadingPhotos(false);
    }
  };

  const removePhoto = (index: number) => {
    set("agencyPhotos", form.agencyPhotos.filter((_, i) => i !== index));
  };

  const handleCreate = async () => {
    if (!validate() || !user) return;
    setCreating(true);
    try {
      const result = await createNewAgency({
        ownerId: user.id,
        name: form.name.trim(),
        logoUrl: form.logoUrl,
        country: form.country || undefined,
        city: form.city || undefined,
        contactPhone: form.contactPhone || null,
        contactEmail: form.contactEmail || null,
        whatsapp: form.whatsapp || null,
        telegram: form.telegram || null,
        instagram: form.instagram || null,
        description: form.description || null,
        foundedYear: form.foundedYear ? parseInt(form.foundedYear, 10) : null,
        address: form.address || null,
        agencyPhotos: form.agencyPhotos.length > 0 ? form.agencyPhotos : null,
        licenseNumber: form.licenseNumber || null,
        licenseIssuingOrg: form.licenseIssuingOrg || null,
      });
      if (result.company) {
        switchAgency(result.company.id);
        refresh();
        toast({
          title: "Agency created!",
          description: `${result.company.name} is ready. Your Agency Code is ${result.company.agency_code ?? "auto-generated"}.`,
        });
        navigate("/consulting/dashboard", { replace: true });
      } else {
        toast({
          title: "Failed to create agency",
          description: result.error ?? "Unknown error",
          variant: "destructive",
        });
      }
    } catch (err) {
      toast({
        title: "Failed to create agency",
        description: err instanceof Error ? err.message : "Unknown error",
        variant: "destructive",
      });
    } finally {
      setCreating(false);
    }
  };

  return (
    <div className="min-h-screen bg-background">
      {/* Header */}
      <div className="border-b border-white/[0.06]">
        <div className="mx-auto flex max-w-2xl items-center gap-3 px-6 py-5">
          <button
            onClick={() => navigate("/consulting/workspace")}
            className="flex h-9 w-9 items-center justify-center rounded-xl bg-white/[0.04] text-muted-foreground transition hover:text-foreground"
          >
            <ArrowLeft className="h-5 w-5" />
          </button>
          <h1 className="font-display text-xl font-bold text-foreground">Create Agency</h1>
        </div>
      </div>

      {/* Form */}
      <div className="mx-auto max-w-2xl px-6 py-8">
        <motion.div
          initial={{ opacity: 0, y: 10 }}
          animate={{ opacity: 1, y: 0 }}
          transition={springIn}
          className="rounded-2xl border border-white/[0.06] bg-white/[0.02] p-6 lg:p-8"
        >
          {/* Logo upload */}
          <div className="mb-6 flex flex-col items-center">
            <button
              onClick={() => fileRef.current?.click()}
              disabled={uploadingLogo}
              className={cn(
                "group relative flex h-24 w-24 items-center justify-center overflow-hidden rounded-2xl border-2 transition",
                errors.logoUrl
                  ? "border-destructive/40"
                  : "border-dashed border-white/10 hover:border-primary/30",
              )}
            >
              {form.logoUrl ? (
                <img src={form.logoUrl} alt="" className="h-full w-full object-cover" />
              ) : uploadingLogo ? (
                <Loader2 className="h-6 w-6 animate-spin text-muted-foreground" />
              ) : (
                <div className="flex flex-col items-center gap-1.5 text-muted-foreground">
                  <Upload className="h-6 w-6" />
                  <span className="text-[10px] font-medium">Upload Logo</span>
                </div>
              )}
            </button>
            <input
              ref={fileRef}
              type="file"
              accept="image/*"
              className="hidden"
              onChange={(e) => {
                const file = e.target.files?.[0];
                if (file) handleLogoUpload(file);
                e.target.value = "";
              }}
            />
            <p className={cn("mt-2 text-xs", errors.logoUrl ? "text-destructive" : "text-muted-foreground")}>
              {errors.logoUrl ?? "Logo is required · PNG or JPG, max 2 MB"}
            </p>
          </div>

          {/* Name */}
          <div className="mb-5">
            <label className="mb-1.5 block text-sm font-semibold text-foreground">
              Agency Name <span className="text-destructive">*</span>
            </label>
            <input
              value={form.name}
              onChange={(e) => set("name", e.target.value)}
              placeholder="e.g. Global Visa & Travel"
              className={cn(
                "w-full rounded-xl border bg-white/[0.03] px-4 py-3 text-sm text-foreground placeholder:text-muted-foreground/60 focus:outline-none",
                errors.name
                  ? "border-destructive/40 focus:border-destructive"
                  : "border-white/[0.06] focus:border-primary/40",
              )}
            />
            {errors.name && <p className="mt-1.5 text-xs text-destructive">{errors.name}</p>}
          </div>

          {/* Country + City */}
          <div className="mb-5 grid gap-4 sm:grid-cols-2">
            <div>
              <label className="mb-1.5 block text-sm font-semibold text-foreground">
                Country <span className="text-destructive">*</span>
              </label>
              <select
                value={form.country}
                onChange={(e) => set("country", e.target.value)}
                className={cn(
                  "w-full rounded-xl border bg-white/[0.03] px-4 py-3 text-sm text-foreground focus:outline-none",
                  errors.country
                    ? "border-destructive/40 focus:border-destructive"
                    : "border-white/[0.06] focus:border-primary/40",
                )}
              >
                <option value="">Select country…</option>
                {COUNTRIES.map((c) => (
                  <option key={c.id} value={c.name}>{c.name}</option>
                ))}
              </select>
              {errors.country && <p className="mt-1.5 text-xs text-destructive">{errors.country}</p>}
            </div>
            <div>
              <label className="mb-1.5 block text-sm font-semibold text-muted-foreground">City</label>
              <input
                value={form.city}
                onChange={(e) => set("city", e.target.value)}
                placeholder="e.g. Tashkent"
                className="w-full rounded-xl border border-white/[0.06] bg-white/[0.03] px-4 py-3 text-sm text-foreground placeholder:text-muted-foreground/60 focus:border-primary/40 focus:outline-none"
              />
            </div>
          </div>

          {/* Contact: Phone + Email */}
          <div className="mb-5 grid gap-4 sm:grid-cols-2">
            <div>
              <label className="mb-1.5 flex items-center gap-1.5 text-sm font-semibold text-muted-foreground">
                <Phone className="h-3.5 w-3.5" /> Phone
              </label>
              <input
                value={form.contactPhone}
                onChange={(e) => set("contactPhone", e.target.value)}
                placeholder="+998 90 123 45 67"
                className="w-full rounded-xl border border-white/[0.06] bg-white/[0.03] px-4 py-3 text-sm text-foreground placeholder:text-muted-foreground/60 focus:border-primary/40 focus:outline-none"
              />
            </div>
            <div>
              <label className="mb-1.5 flex items-center gap-1.5 text-sm font-semibold text-muted-foreground">
                <Mail className="h-3.5 w-3.5" /> Email
              </label>
              <input
                value={form.contactEmail}
                onChange={(e) => set("contactEmail", e.target.value)}
                placeholder="info@agency.com"
                className="w-full rounded-xl border border-white/[0.06] bg-white/[0.03] px-4 py-3 text-sm text-foreground placeholder:text-muted-foreground/60 focus:border-primary/40 focus:outline-none"
              />
            </div>
          </div>

          {/* Social: WhatsApp + Telegram */}
          <div className="mb-5 grid gap-4 sm:grid-cols-2">
            <div>
              <label className="mb-1.5 flex items-center gap-1.5 text-sm font-semibold text-muted-foreground">
                <MessageCircle className="h-3.5 w-3.5" /> WhatsApp
              </label>
              <input
                value={form.whatsapp}
                onChange={(e) => set("whatsapp", e.target.value)}
                placeholder="+998 90 123 45 67"
                className="w-full rounded-xl border border-white/[0.06] bg-white/[0.03] px-4 py-3 text-sm text-foreground placeholder:text-muted-foreground/60 focus:border-primary/40 focus:outline-none"
              />
            </div>
            <div>
              <label className="mb-1.5 flex items-center gap-1.5 text-sm font-semibold text-muted-foreground">
                <Send className="h-3.5 w-3.5" /> Telegram
              </label>
              <input
                value={form.telegram}
                onChange={(e) => set("telegram", e.target.value)}
                placeholder="@agency_handle"
                className="w-full rounded-xl border border-white/[0.06] bg-white/[0.03] px-4 py-3 text-sm text-foreground placeholder:text-muted-foreground/60 focus:border-primary/40 focus:outline-none"
              />
            </div>
          </div>

          {/* Instagram + Founded Year */}
          <div className="mb-5 grid gap-4 sm:grid-cols-2">
            <div>
              <label className="mb-1.5 flex items-center gap-1.5 text-sm font-semibold text-muted-foreground">
                <Instagram className="h-3.5 w-3.5" /> Instagram
              </label>
              <input
                value={form.instagram}
                onChange={(e) => set("instagram", e.target.value)}
                placeholder="@agency_insta"
                className="w-full rounded-xl border border-white/[0.06] bg-white/[0.03] px-4 py-3 text-sm text-foreground placeholder:text-muted-foreground/60 focus:border-primary/40 focus:outline-none"
              />
            </div>
            <div>
              <label className="mb-1.5 flex items-center gap-1.5 text-sm font-semibold text-muted-foreground">
                <Calendar className="h-3.5 w-3.5" /> Founded Year
              </label>
              <input
                value={form.foundedYear}
                onChange={(e) => set("foundedYear", e.target.value.replace(/[^0-9]/g, "").slice(0, 4))}
                placeholder="2015"
                inputMode="numeric"
                className="w-full rounded-xl border border-white/[0.06] bg-white/[0.03] px-4 py-3 text-sm text-foreground placeholder:text-muted-foreground/60 focus:border-primary/40 focus:outline-none"
              />
            </div>
          </div>

          {/* Address / Main Office */}
          <div className="mb-5">
            <label className="mb-1.5 flex items-center gap-1.5 text-sm font-semibold text-muted-foreground">
              <MapPin className="h-3.5 w-3.5" /> Main Office / Location
            </label>
            <input
              value={form.address}
              onChange={(e) => set("address", e.target.value)}
              placeholder="123 Main Street, Tashkent, Uzbekistan"
              className="w-full rounded-xl border border-white/[0.06] bg-white/[0.03] px-4 py-3 text-sm text-foreground placeholder:text-muted-foreground/60 focus:border-primary/40 focus:outline-none"
            />
          </div>

          {/* Description */}
          <div className="mb-5">
            <label className="mb-1.5 block text-sm font-semibold text-muted-foreground">
              Short Description
            </label>
            <textarea
              value={form.description}
              onChange={(e) => set("description", e.target.value)}
              rows={3}
              placeholder="Briefly describe your travel agency, services, and specialties…"
              className="w-full resize-none rounded-xl border border-white/[0.06] bg-white/[0.03] px-4 py-3 text-sm text-foreground placeholder:text-muted-foreground/60 focus:border-primary/40 focus:outline-none"
            />
          </div>

          {/* Agency Photos */}
          <div className="mb-5">
            <label className="mb-1.5 flex items-center gap-1.5 text-sm font-semibold text-muted-foreground">
              <ImageIcon className="h-3.5 w-3.5" /> Agency Photos
              <span className="text-muted-foreground/50">(office, team, etc.)</span>
            </label>
            <div className="flex flex-wrap gap-3">
              <AnimatePresence>
                {form.agencyPhotos.map((photo, idx) => (
                  <motion.div
                    key={photo + idx}
                    initial={{ opacity: 0, scale: 0.8 }}
                    animate={{ opacity: 1, scale: 1 }}
                    exit={{ opacity: 0, scale: 0.8 }}
                    className="group relative h-20 w-20 overflow-hidden rounded-xl border border-white/[0.06]"
                  >
                    <img src={photo} alt="" className="h-full w-full object-cover" />
                    <button
                      onClick={() => removePhoto(idx)}
                      className="absolute inset-0 flex items-center justify-center bg-black/60 opacity-0 transition group-hover:opacity-100"
                    >
                      <X className="h-4 w-4 text-white" />
                    </button>
                  </motion.div>
                ))}
              </AnimatePresence>
              <button
                onClick={() => photoRef.current?.click()}
                disabled={uploadingPhotos}
                className="flex h-20 w-20 items-center justify-center rounded-xl border-2 border-dashed border-white/10 bg-white/[0.02] text-muted-foreground transition hover:border-primary/30 hover:text-primary"
              >
                {uploadingPhotos ? (
                  <Loader2 className="h-5 w-5 animate-spin" />
                ) : (
                  <div className="flex flex-col items-center gap-1">
                    <Upload className="h-4 w-4" />
                    <span className="text-[9px] font-medium">Add Photo</span>
                  </div>
                )}
              </button>
            </div>
            <input
              ref={photoRef}
              type="file"
              accept="image/*"
              multiple
              className="hidden"
              onChange={(e) => {
                if (e.target.files && e.target.files.length > 0) {
                  handlePhotoUpload(e.target.files);
                }
                e.target.value = "";
              }}
            />
            <p className="mt-1.5 text-xs text-muted-foreground">PNG or JPG, max 3 MB each</p>
          </div>

          {/* License info (optional — existing approval system) */}
          <div className="mb-6 rounded-xl border border-white/[0.06] bg-white/[0.01] p-4">
            <label className="mb-3 flex items-center gap-1.5 text-sm font-semibold text-foreground">
              <FileText className="h-3.5 w-3.5" /> License Information
              <span className="text-muted-foreground/50">(optional — for verification later)</span>
            </label>
            <div className="grid gap-3 sm:grid-cols-2">
              <div>
                <label className="mb-1 block text-xs text-muted-foreground">License Number</label>
                <input
                  value={form.licenseNumber}
                  onChange={(e) => set("licenseNumber", e.target.value)}
                  placeholder="e.g. TRV-2024-00123"
                  className="w-full rounded-lg border border-white/[0.06] bg-white/[0.03] px-3 py-2 text-xs text-foreground placeholder:text-muted-foreground/60 focus:border-primary/40 focus:outline-none"
                />
              </div>
              <div>
                <label className="mb-1 block text-xs text-muted-foreground">Issuing Organization</label>
                <input
                  value={form.licenseIssuingOrg}
                  onChange={(e) => set("licenseIssuingOrg", e.target.value)}
                  placeholder="e.g. Ministry of Tourism"
                  className="w-full rounded-lg border border-white/[0.06] bg-white/[0.03] px-3 py-2 text-xs text-foreground placeholder:text-muted-foreground/60 focus:border-primary/40 focus:outline-none"
                />
              </div>
            </div>
          </div>

          {/* Info note */}
          <div className="mb-6 flex items-start gap-3 rounded-xl border border-primary/15 bg-primary/[0.04] p-4">
            <Sparkles className="mt-0.5 h-4 w-4 shrink-0 text-primary" />
            <p className="text-xs text-muted-foreground">
              A unique <strong className="text-foreground">Agency Code</strong> will be auto-generated.
              Share it with team members so they can request to join your agency.
              You can complete your agency profile later in the Profile section.
            </p>
          </div>

          {/* Actions */}
          <div className="flex gap-3">
            <button
              onClick={handleCreate}
              disabled={creating || uploadingLogo}
              className="flex flex-1 items-center justify-center gap-2 rounded-xl bg-primary px-6 py-3 text-sm font-bold text-primary-foreground transition hover:bg-primary/90 disabled:opacity-50"
            >
              {creating ? (
                <>
                  <Loader2 className="h-4 w-4 animate-spin" />
                  Creating…
                </>
              ) : (
                <>
                  <Check className="h-4 w-4" />
                  Create Agency
                </>
              )}
            </button>
            <button
              onClick={() => navigate("/consulting/workspace")}
              disabled={creating}
              className="rounded-xl border border-white/[0.06] bg-white/[0.02] px-6 py-3 text-sm font-semibold text-muted-foreground transition hover:text-foreground"
            >
              Cancel
            </button>
          </div>
        </motion.div>
      </div>
    </div>
  );
}

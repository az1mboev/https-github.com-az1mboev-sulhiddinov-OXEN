import { useRef, useState } from "react";
import { motion } from "framer-motion";
import { useNavigate } from "react-router-dom";
import { Building2, Upload, Loader2, ArrowLeft, Check, Sparkles } from "lucide-react";

import { useAuth } from "@/contexts/AuthContext";
import { useConsulting } from "@/contexts/ConsultingContext";
import { useSEO } from "@/hooks/use-seo";
import { toast } from "@/hooks/use-toast";
import { createNewAgency, uploadConsultingAsset } from "@/lib/consulting";
import { COUNTRIES } from "@/data/countries";
import { cn } from "@/lib/utils";

const springIn = {
  type: "spring" as const,
  stiffness: 260,
  damping: 26,
};

interface FormData {
  name: string;
  country: string;
  city: string;
  logoUrl: string | null;
}

interface FormErrors {
  name?: string;
}

/**
 * CreateAgency — form to create a new agency.
 *
 * On submit:
 * - Creates consulting_companies row (agency_code auto-generated by DB trigger)
 * - Creates consulting_members row with role=owner
 * - Sets this agency as active
 * - Redirects to dashboard
 */
export default function CreateAgency() {
  const navigate = useNavigate();
  const { user } = useAuth();
  const { switchAgency, refresh } = useConsulting();
  const fileRef = useRef<HTMLInputElement>(null);

  const [form, setForm] = useState<FormData>({
    name: "",
    country: "",
    city: "",
    logoUrl: null,
  });
  const [errors, setErrors] = useState<FormErrors>({});
  const [uploadingLogo, setUploadingLogo] = useState(false);
  const [creating, setCreating] = useState(false);

  useSEO({
    title: "Create Agency | OXEN CRM",
    description: "Create a new travel agency workspace.",
  });

  const set = <K extends keyof FormData>(key: K, value: FormData[K]) => {
    setForm((prev) => ({ ...prev, [key]: value }));
    if (key === "name" && errors.name) setErrors({});
  };

  const validate = (): boolean => {
    const errs: FormErrors = {};
    if (!form.name.trim()) {
      errs.name = "Agency name is required.";
    } else if (form.name.trim().length < 2) {
      errs.name = "Name must be at least 2 characters.";
    }
    setErrors(errs);
    return Object.keys(errs).length === 0;
  };

  const handleLogoUpload = async (file: File) => {
    if (!user) return;
    if (file.size > 2 * 1024 * 1024) {
      toast({ title: "Image too large", description: "Max 2 MB.", variant: "destructive" });
      return;
    }
    // Preview locally first
    const reader = new FileReader();
    reader.onload = () => set("logoUrl", reader.result as string);
    reader.readAsDataURL(file);

    // Upload to storage
    setUploadingLogo(true);
    try {
      const url = await uploadConsultingAsset(file, `temp-logos/${user.id}/logo-${Date.now()}`);
      if (url) {
        set("logoUrl", url);
        toast({ title: "Logo uploaded" });
      }
    } catch {
      // Keep the data URL preview — will upload again after company is created
    } finally {
      setUploadingLogo(false);
    }
  };

  const handleCreate = async () => {
    if (!validate() || !user) return;
    setCreating(true);
    try {
      const result = await createNewAgency({
        ownerId: user.id,
        name: form.name.trim(),
        logoUrl: form.logoUrl,
        country: form.country || undefined,
        city: form.city || undefined,
      });
      if (result.company) {
        switchAgency(result.company.id);
        refresh();
        toast({
          title: "Agency created!",
          description: `${result.company.name} is ready. Your Agency Code is ${result.company.agency_code ?? "auto-generated"}.`,
        });
        navigate("/consulting/dashboard", { replace: true });
      } else {
        toast({
          title: "Failed to create agency",
          description: result.error ?? "Unknown error",
          variant: "destructive",
        });
      }
    } catch (err) {
      toast({
        title: "Failed to create agency",
        description: err instanceof Error ? err.message : "Unknown error",
        variant: "destructive",
      });
    } finally {
      setCreating(false);
    }
  };

  return (
    <div className="min-h-screen bg-background">
      {/* Header */}
      <div className="border-b border-white/[0.06]">
        <div className="mx-auto flex max-w-2xl items-center gap-3 px-6 py-5">
          <button
            onClick={() => navigate("/consulting/workspace")}
            className="flex h-9 w-9 items-center justify-center rounded-xl bg-white/[0.04] text-muted-foreground transition hover:text-foreground"
          >
            <ArrowLeft className="h-5 w-5" />
          </button>
          <h1 className="font-display text-xl font-bold text-foreground">Create Agency</h1>
        </div>
      </div>

      {/* Form */}
      <div className="mx-auto max-w-2xl px-6 py-8">
        <motion.div
          initial={{ opacity: 0, y: 10 }}
          animate={{ opacity: 1, y: 0 }}
          transition={springIn}
          className="rounded-2xl border border-white/[0.06] bg-white/[0.02] p-6 lg:p-8"
        >
          {/* Logo upload */}
          <div className="mb-6 flex flex-col items-center">
            <button
              onClick={() => fileRef.current?.click()}
              disabled={uploadingLogo}
              className="group relative flex h-24 w-24 items-center justify-center overflow-hidden rounded-2xl border-2 border-dashed border-white/10 bg-white/[0.02] transition hover:border-primary/30"
            >
              {form.logoUrl ? (
                <img src={form.logoUrl} alt="" className="h-full w-full object-cover" />
              ) : uploadingLogo ? (
                <Loader2 className="h-6 w-6 animate-spin text-muted-foreground" />
              ) : (
                <div className="flex flex-col items-center gap-1.5 text-muted-foreground">
                  <Upload className="h-6 w-6" />
                  <span className="text-[10px] font-medium">Upload Logo</span>
                </div>
              )}
            </button>
            <input
              ref={fileRef}
              type="file"
              accept="image/*"
              className="hidden"
              onChange={(e) => {
                const file = e.target.files?.[0];
                if (file) handleLogoUpload(file);
              }}
            />
            <p className="mt-2 text-xs text-muted-foreground">PNG or JPG, max 2 MB</p>
          </div>

          {/* Name */}
          <div className="mb-5">
            <label className="mb-1.5 block text-sm font-semibold text-foreground">
              Agency Name <span className="text-destructive">*</span>
            </label>
            <input
              value={form.name}
              onChange={(e) => set("name", e.target.value)}
              placeholder="e.g. Global Visa & Travel"
              className={cn(
                "w-full rounded-xl border bg-white/[0.03] px-4 py-3 text-sm text-foreground placeholder:text-muted-foreground/60 focus:outline-none",
                errors.name
                  ? "border-destructive/40 focus:border-destructive"
                  : "border-white/[0.06] focus:border-primary/40",
              )}
            />
            {errors.name && (
              <p className="mt-1.5 text-xs text-destructive">{errors.name}</p>
            )}
          </div>

          {/* Country + City */}
          <div className="mb-6 grid gap-4 sm:grid-cols-2">
            <div>
              <label className="mb-1.5 block text-sm font-semibold text-muted-foreground">
                Country <span className="text-muted-foreground/50">(optional)</span>
              </label>
              <select
                value={form.country}
                onChange={(e) => set("country", e.target.value)}
                className="w-full rounded-xl border border-white/[0.06] bg-white/[0.03] px-4 py-3 text-sm text-foreground focus:border-primary/40 focus:outline-none"
              >
                <option value="">Select country…</option>
                {COUNTRIES.map((c) => (
                  <option key={c.id} value={c.name}>
                    {c.name}
                  </option>
                ))}
              </select>
            </div>
            <div>
              <label className="mb-1.5 block text-sm font-semibold text-muted-foreground">
                City <span className="text-muted-foreground/50">(optional)</span>
              </label>
              <input
                value={form.city}
                onChange={(e) => set("city", e.target.value)}
                placeholder="e.g. Tashkent"
                className="w-full rounded-xl border border-white/[0.06] bg-white/[0.03] px-4 py-3 text-sm text-foreground placeholder:text-muted-foreground/60 focus:border-primary/40 focus:outline-none"
              />
            </div>
          </div>

          {/* Info note */}
          <div className="mb-6 flex items-start gap-3 rounded-xl border border-primary/15 bg-primary/[0.04] p-4">
            <Sparkles className="mt-0.5 h-4 w-4 shrink-0 text-primary" />
            <p className="text-xs text-muted-foreground">
              A unique <strong className="text-foreground">Agency Code</strong> will be auto-generated.
              Share it with team members so they can request to join your agency.
              You can complete your agency profile later in the Profile section.
            </p>
          </div>

          {/* Actions */}
          <div className="flex gap-3">
            <button
              onClick={handleCreate}
              disabled={creating || uploadingLogo}
              className="flex flex-1 items-center justify-center gap-2 rounded-xl bg-primary px-6 py-3 text-sm font-bold text-primary-foreground transition hover:bg-primary/90 disabled:opacity-50"
            >
              {creating ? (
                <>
                  <Loader2 className="h-4 w-4 animate-spin" />
                  Creating…
                </>
              ) : (
                <>
                  <Check className="h-4 w-4" />
                  Create Agency
                </>
              )}
            </button>
            <button
              onClick={() => navigate("/consulting/workspace")}
              disabled={creating}
              className="rounded-xl border border-white/[0.06] bg-white/[0.02] px-6 py-3 text-sm font-semibold text-muted-foreground transition hover:text-foreground"
            >
              Cancel
            </button>
          </div>
        </motion.div>
      </div>
    </div>
  );
}

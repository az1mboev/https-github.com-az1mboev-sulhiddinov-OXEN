/** Build flagcdn URL — SVG for razor-sharp rendering at any size, PNG fallback */
export function getFlagUrl(isoCode: string): string {
  return `https://flagcdn.com/${isoCode}.svg`;
}

/** PNG fallback for browsers that don't render SVGs well */
export function getFlagPngUrl(isoCode: string): string {
  return `https://flagcdn.com/w640/${isoCode}.png`;
}

/** Get ISO code for a country by its id, null if not found */
export function getCountryIso(countryId: string): string | null {
  return COUNTRY_ISO[countryId] ?? null;
}

/** Get area for a country by its id, null if not found */
export function getCountryArea(countryId: string): number | null {
  return COUNTRY_AREA[countryId] ?? null;
}

/** Format area in km² with thousands separators */
export function formatArea(km2: number): string {
  if (km2 >= 1_000_000) return `${(km2 / 1_000_000).toFixed(2)}M km²`;
  return `${km2.toLocaleString()} km²`;
}

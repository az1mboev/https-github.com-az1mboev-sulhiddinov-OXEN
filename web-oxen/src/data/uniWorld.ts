/* ── Compact university tuple: [name, city, lat, lng, qs?, students?] ── */
type UT = readonly [string, string, number, number, number?, number?];

function slug(name: string): string {
  return name.toLowerCase().replace(/[^a-z0-9]+/g, "-").replace(/^-|-$/g, "");
}

function expand(country: string, unis: UT[]): UniSeed[] {
  const d = CM[country];
  if (!d) return [];
  return unis.map(([name, city, lat, lng, qs, students]) => {
    const q = qs ?? 800;
    const s = students ?? Math.max(8000, Math.round(20000 - q * 8));
    return {
      id: "w-" + slug(name),
      name,
      country,
      flag: d[0],
      city,
      continent: d[1],
      lat,
      lng,
      qsRanking: q,
      tuitionNumeric: d[3][0],
      tuition: d[3][1],
      type: "public" as const,
      language: d[2],
      hasScholarship: true,
      acceptanceRate: Math.min(80, Math.max(5, Math.round(q / 15))),
      ielts: d[4],
      toefl: d[5],
      sat: d[6],
      act: d[7],
      studentsCount: s,
      programsCount: Math.max(20, Math.round(s / 200)),
      deadline: d[8],
      employmentRate: Math.min(95, Math.max(70, d[11] - Math.floor(q / 200))),
      livingCost: d[9],
      housingAvailable: d[10],
    };
  });
}

